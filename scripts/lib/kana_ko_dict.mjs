const DICT_KEYS = Object.keys(TERM_DICT).sort((a, b) => b.length - a.length);

export const KANA_RE = /[぀-ゟ゠-ヿ]/;

// Translate one contiguous kana run via greedy longest-match; null when a
// segment is not covered by the dictionary (caller should skip, not guess).
export function translateKanaRun(run) {
  const out = [];
  let pos = 0;
  while (pos < run.length) {
    if (run[pos] === "ー" || run[pos] === "・" || run[pos] === " ") { pos += 1; continue; }
    const hit = DICT_KEYS.find((key) => run.startsWith(key, pos));
    if (!hit) return null;
    out.push(TERM_DICT[hit]);
    pos += hit.length;
  }
  return out.join(" ");
}

// Translate every kana run inside a full display name, preserving all other
// characters (codes, kanji, brackets). All-or-nothing: if any run fails,
// returns null so callers keep the original name instead of a hybrid.
export function translateDisplayName(name) {
  const source = String(name || "");
  if (!KANA_RE.test(source)) return null;
  const segments = source.match(/[぀-ゟ゠-ヿー・]+|[^぀-ゟ゠-ヿー・]+/g) || [];
  const out = [];
  for (const seg of segments) {
    if (KANA_RE.test(seg)) {
      const translated = translateKanaRun(seg.replace(/\s+/g, ""));
      if (translated === null) return null;
      out.push(` ${translated} `);
    } else {
      out.push(seg);
    }
  }
  const result = out.join("").replace(/\s+/g, " ").trim();
  return result && result !== source ? result : null;
}
